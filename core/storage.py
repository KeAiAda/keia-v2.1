# -------------------------------------------------------------------
# Простое хранилище для Keia-v2.
# Пока умеет: читать JSON, писать JSON (атомарно), читать текст,
# дописывать строку в файл.
# Позже добавим кэш и локи — когда они реально понадобятся.
# -------------------------------------------------------------------

import json
# json — стандартный модуль для работы с JSON-форматом (сериализация/десериализация).

import os
# os — нужен для os.replace (атомарная подмена файла) и os.makedirs (создание папок).

import tempfile
# tempfile — умеет создавать временные файлы с уникальным именем.
# Мы используем mkstemp() — он создаёт файл и возвращает (дискриптор, путь).

from pathlib import Path
# Path — удобная работа с путями. Наш config.py уже использует его.


# -------------------------------------------------------------------
# 1. Атомарная запись текста
# -------------------------------------------------------------------

def atomic_write_text(path: Path, text: str) -> None:
    """
    Записать text в файл path атомарно.
    Либо запись проходит полностью, либо файл остаётся прежним.
    """
    # Преобразуем в Path, если пришёл str — на всякий случай.
    path = Path(path)

    # Убеждаемся, что папка, в которой будет файл, существует.
    # parents=True — создать и родительские папки (например, memory/logs/).
    # exist_ok=True — не падать с ошибкой, если папка уже есть.
    path.parent.mkdir(parents=True, exist_ok=True)

    # Создаём временный файл В ТОЙ ЖЕ ПАПКЕ, что и целевой.
    # Почему в той же: os.replace работает атомарно только в пределах
    # одной файловой системы. Если временный файл в /tmp, а целевой
    # в /home — это будет уже НЕ атомарно (копирование между ФС).
    fd, tmp_path = tempfile.mkstemp(
        dir=str(path.parent),   # папка для временного файла
        prefix=".tmp_",         # префикс имени (точка = скрытый файл)
        suffix=".json",         # суффикс (просто для наглядности)
    )

    try:
        # os.fdopen оборачивает числовой дескриптор в файловый объект Python.
        # "w" — режим записи (стирает содержимое, если файл есть).
        # encoding="utf-8" — важно для русского текста и эмодзи.
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            f.write(text)   # пишем весь текст за раз

        # os.replace — атомарная операция "заменить файл".
        # Если path существует — он будет заменён. Если нет — создан.
        # Это и есть момент "вклеивания листка": либо старое, либо новое.
        os.replace(tmp_path, path)

    except Exception:
        # Если что-то упало в процессе — пытаемся удалить временный файл,
        # чтобы не мусорить. Если удалить не удалось — не страшно, просто
        # оставим (это не влияет на работу).
        try:
            os.unlink(tmp_path)
        except OSError:
            pass
        # Пробрасываем исключение наверх — пусть вызывающий код знает,
        # что запись не удалась.
        raise


# -------------------------------------------------------------------
# 2. Запись JSON (обёртка над atomic_write_text)
# -------------------------------------------------------------------

def atomic_write_json(path: Path, data) -> None:
    """
    Сохранить data как JSON, атомарно.
    data может быть dict, list, число, строка — что угодно, что сериализуется.
    """
    # json.dumps превращает Python-объект в строку.
    # ensure_ascii=False — чтобы русские буквы остались русскими, а не \uXXXX.
    # indent=4 — читаемый вывод (для отладки удобно открывать глазами).
    text = json.dumps(data, ensure_ascii=False, indent=4)

    # Делегируем всю работу атомарной записи текста.
    atomic_write_text(path, text)


# -------------------------------------------------------------------
# 3. Чтение JSON
# -------------------------------------------------------------------

def load_json(path: Path, default=None):
    """
    Прочитать JSON из файла.
    Если файла нет или он битый — вернуть default (по умолчанию None).
    """
    path = Path(path)

    # Если файла нет — сразу возвращаем default.
    if not path.exists():
        return default

    try:
        # open с encoding="utf-8" — обязательно для русского текста.
        with open(path, "r", encoding="utf-8") as f:
            return json.load(f)

    except (json.JSONDecodeError, OSError):
        # json.JSONDecodeError — файл есть, но внутри невалидный JSON.
        # OSError — проблемы с чтением (нет прав, файл занят и т.д.).
        # В обоих случаях возвращаем default — не падаем.
        return default


# -------------------------------------------------------------------
# 4. Чтение текстового файла
# -------------------------------------------------------------------

def load_text(path: Path) -> str:
    """
    Прочитать текстовый файл.
    Если файла нет — вернуть пустую строку.
    """
    path = Path(path)

    if not path.exists():
        return ""

    with open(path, "r", encoding="utf-8") as f:
        return f.read()


# -------------------------------------------------------------------
# 5. Дописать строку в конец файла
# -------------------------------------------------------------------

def append_line(path: Path, text: str) -> None:
    """
    Дописать text в конец файла + перевод строки.
    Используется для логов: не перезаписываем, только добавляем.
    """
    path = Path(path)

    # Создать родительские папки, если их нет.
    path.parent.mkdir(parents=True, exist_ok=True)

    # "a" — append-режим: НЕ стирает файл, а пишет в конец.
    # Если файла нет — создаст его.
    with open(path, "a", encoding="utf-8") as f:
        f.write(text + "\n")