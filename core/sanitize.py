import re

# -------------------------------------------------------------------
# 1. Паттерны для проверки на "ассистента" (is_bad)
# -------------------------------------------------------------------

# Если ответ содержит эти фразы, значит модель "сломалась" и 
# начала вести себя как тупой поисковик. Мы такие ответы не сохраняем в историю.
BAD_PATTERNS = [
    "как я могу помочь",
    "чем могу помочь",
    "чем могу быть полезна",
    "я могу помочь",
    "могу помочь составить",
    "могу помочь с",
    "пожалуйста, укажи",
    "пожалуйста, повтори",
    "пожалуйста, скажи",
    "укажи на какие",
    "укажите",
    "какую тему для",
    "о чём поговорим",
    "о чем поговорим",
    "я ассистент",
    "служба поддержки",
    "как ии",
    "как языковая модель",
    "я не понял вас",
    "я не поняла вас",
    "извините за",
    "если у меня нет информации",
    "если у тебя нет информации",
    "ваш вопрос",
    "ваше сообщение",
    "как будто вы говорили",
    "чем я могу быть полезна",
]

# -------------------------------------------------------------------
# 2. Белый список символов (SAFE_CHARS_PATTERN)
# -------------------------------------------------------------------
# Вместо того чтобы запрещать эмодзи по одному (мы всё равно не угонимся за обновлениями Unicode),
# мы РАЗРЕШАЕМ только безопасные символы (буквы, цифры, знаки препинания). 
# Всё, что не входит в этот список (смайлики, иероглифы, странные символы) — безжалостно удаляется.

SAFE_CHARS_PATTERN = re.compile(
    r"[^"
    r"\u0009\u000A\u000D"            # табуляция, перенос строки, возврат каретки
    r"\u0020-\u007E"                 # ASCII (латиница, цифры, пунктуация)
    r"\u00A0-\u00FF"                 # Latin-1
    r"\u0400-\u04FF"                 # Кириллица
    r"\u2010-\u2015"                 # тире и дефисы
    r"\u2018-\u201D"                 # умные кавычки
    r"\u2026"                        # многоточие
    r"\u2039\u203A"                  # угловые кавычки
    r"\u00AB\u00BB"                  # двойные угловые кавычки
    r"\u20AC"                        # евро
    r"\u2116"                        # знак номера
    r"]"
)

# Старый паттерн для проверки (оставим, чтобы is_bad работал)
BAD_CHARS_PATTERN = re.compile(
    r"[\U0001F300-\U0001F9FF"     # эмодзи-блоки
    r"\U00002600-\U000027BF"        # разные символы
    r"\U0001F600-\U0001F64F"        # смайлики
    r"]"
)


def is_bad(reply: str) -> bool:
    """
    Проверить, содержит ли ответ модели плохие паттерны.
    Возвращает True, если ответ плохой (ассистентский или с эмодзи).
    """
    lower = reply.lower()
    if any(pattern in lower for pattern in BAD_PATTERNS):
        return True
    if BAD_CHARS_PATTERN.search(reply):
        return True
    return False


def repair(reply: str) -> str:
    """
    Мягкая постобработка. Делает текст красивым и убирает мусор.
    """
    if not reply:
        return reply
        
    original = reply # Запоминаем оригинал, вдруг мы случайно удалим всё

    # 1. Убираем всё, что не в белом списке (эмодзи, иероглифы, странные символы).
    reply = SAFE_CHARS_PATTERN.sub("", reply)

    # 2. Заменяем формальные обращения на неформальные.
    replacements = [
        ("Извините", "Ой"), ("извините", "ой"),
        ("Пожалуйста", "Мм"), ("пожалуйста", "мм"),
        ("вас", "тебя"), ("Вас", "Тебя"),
        ("ваш ", "твой "), ("Ваш ", "Твой "),
        ("вы ", "ты "), ("Вы ", "Ты "),
    ]
    for old, new in replacements:
        reply = reply.replace(old, new)

    # 3. Убираем лишние пробелы, НО СОХРАНЯЕМ ПЕРЕНОСЫ СТРОК (важно для абзацев!)
    # Заменяем множественные пробелы и табы на один пробел
    reply = re.sub(r"[ \t]+", " ", reply)
    # Убираем больше двух переносов строк подряд (чтобы не было гигантских пустот)
    reply = re.sub(r"\n{3,}", "\n\n", reply)
    # Убираем пробелы в начале и конце
    reply = reply.strip()

    # 4. УМНАЯ ЗАМЕНА ДЕЙСТВИЙ (Фикс курсива)
    # Сначала удаляем ВСЕ звездочки, которые поставила модель, 
    # чтобы не было незакрытых или сломанных.
    reply = reply.replace('*', '')

    # Теперь ищем всё, что находится в дефисах (например: -Она хмыкает-),
    # и принудительно оборачиваем текст в звездочки для курсива в Discord.
    # Результат: -*Она хмыкает*-
    reply = re.sub(r'-([^-]+)-', lambda m: f"-*{m.group(1).strip()}*-", reply)

    # 5. ЗАЩИТА: Если после всех чисток текст исчез, но изначально он был — возвращаем оригинал!
    if not reply.strip() and original.strip():
        return original.strip()

