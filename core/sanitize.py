# core/sanitize.py
# -------------------------------------------------------------------
# Фильтр "плохих" ответов модели + мягкая постобработка.
# -------------------------------------------------------------------

import re

# Паттерны ассистентского режима. Все в нижнем регистре.
BAD_PATTERNS = [
    "как я могу помочь",
    "чем могу помочь",
    "чем могу быть полезна",
    "я могу помочь",
    "могу помочь составить",
    "могу помочь с",
    "пожалуйста, укажи",
    "пожалуйста, повтори",
    "пожалуйста, скажи",
    "укажи на какие",
    "укажите",
    "какую тему для",
    "о чём поговорим",
    "о чем поговорим",
    "я ассистент",
    "служба поддержки",
    "как ии",
    "как языковая модель",
    "я не понял вас",
    "я не поняла вас",
    "извините за",
    "если у меня нет информации",
    "если у тебя нет информации",
    "ваш вопрос",
    "ваше сообщение",
    "как будто вы говорили",
    "чем я могу быть полезна",
]

# Плохие символы — Unicode-эмодзи, которые маленькая модель любит.
# Мы хотим ASCII-смайлики типа (: :з ^_^
BAD_CHARS_PATTERN = re.compile(
    r"[\U0001F300-\U0001F9FF"     # эмодзи-блоки
    r"\U00002600-\U000027BF"        # разные символы
    r"\U0001F600-\U0001F64F"        # смайлики
    r"]"
)


def is_bad(reply: str) -> bool:
    """
    Проверить, содержит ли ответ модели плохие паттерны.
    Возвращает True, если ответ плохой.
    """
    lower = reply.lower()
    if any(pattern in lower for pattern in BAD_PATTERNS):
        return True
    if BAD_CHARS_PATTERN.search(reply):
        return True
    return False


def repair(reply: str) -> str:
    """
    Мягкая постобработка: заменяем плохие штуки, даже если ответ
    в целом не плохой. Работает "на выходе".
    """
    # Убираем Unicode-эмодзи.
    reply = BAD_CHARS_PATTERN.sub("", reply)

    # Заменяем формальные обращения на неформальные.
    # Порядок важен: "вас" → "тебя" до "ваш" → "твой", иначе "вас" застрянет.
    replacements = [
        ("Извините", "Ой"),
        ("извините", "ой"),
        ("Извини", "Ой"),
        ("извини", "ой"),
        ("Пожалуйста, повторите", "Повтори ещё раз"),
        ("пожалуйста, повторите", "повтори ещё раз"),
        ("Пожалуйста", "Мм"),
        ("пожалуйста", "мм"),
        ("вас", "тебя"),
        ("Вас", "Тебя"),
        ("ваш ", "твой "),
        ("Ваш ", "Твой "),
        ("ваш", "твой"),      # на случай "ваш." в конце
        ("ваш", "твой"),
        ("вы ", "ты "),
        ("Вы ", "Ты "),
    ]
    for old, new in replacements:
        reply = reply.replace(old, new)

    # Убираем двойные пробелы после замен.
    reply = re.sub(r"\s+", " ", reply).strip()

    return reply