# core/history.py
# -------------------------------------------------------------------
# История диалогов (Кратковременная память).
# Хранит последние N сообщений для каждого пользователя в JSON.
# -------------------------------------------------------------------

import asyncio
# asyncio — нужен для Lock, чтобы два одновременных запроса не испортили историю.

from core import config
from core import storage

# -------------------------------------------------------------------
# 1. Состояние в памяти
# -------------------------------------------------------------------

# Кэш в оперативной памяти: {user_id: [сообщение, сообщение, ...]}
# Читается с диска один раз при старте (в init), потом работаем с ним.
_histories: dict[int, list[dict]] = {}

# Флаг: загружали ли мы уже историю с диска.
_initialized = False

# Блокировка: пока один поток пишет, другой ждёт.
_lock = asyncio.Lock()

# Сколько последних сообщений хранить для одного пользователя.
# 12 сообщений = 6 пар (вопрос-ответ). Этого хватает для контекста.
MAX_HISTORY = 12


# -------------------------------------------------------------------
# 2. Инициализация
# -------------------------------------------------------------------

def init() -> None:
    """
    Загрузить историю из файла в память.
    Вызывается один раз при старте приложения.
    """
    global _histories, _initialized

    # Если уже загружено — не грузим повторно.
    if _initialized:
        return

    # load_json вернёт {} если файла нет или он битый — не упадёт.
    raw = storage.load_json(config.HISTORY_FILE, default={})

    # В JSON ключи — строки. Нам удобнее числа (user_id — это int).
    _histories = {int(k): v for k, v in raw.items()}

    _initialized = True


# -------------------------------------------------------------------
# 3. Сохранение на диск
# -------------------------------------------------------------------

def _save() -> None:
    """Записать текущий кэш _histories в файл на диск."""
    # JSON требует строковых ключей, поэтому конвертируем int -> str.
    to_save = {str(k): v for k, v in _histories.items()}
    
    # atomic_write_json атомарно запишет данные (не повредит файл при выключении).
    storage.atomic_write_json(config.HISTORY_FILE, to_save)


# -------------------------------------------------------------------
# 4. Добавление сообщения
# -------------------------------------------------------------------

async def add(user_id: int, role: str, content: str) -> None:
    """
    Добавить одно сообщение в историю пользователя.
    role: "user" (пользователь) или "assistant" (Кея).
    """
    # Берем блокировку, чтобы избежать race condition.
    async with _lock:
        # setdefault: если для пользователя нет списка — создаст пустой.
        _histories.setdefault(user_id, []).append({
            "role": role,
            "content": content,
        })

        # Обрезаем историю до последних MAX_HISTORY сообщений.
        _histories[user_id] = _histories[user_id][-MAX_HISTORY:]

        # Синхронно сохраняем на диск.
        _save()


# -------------------------------------------------------------------
# 5. Получение истории
# -------------------------------------------------------------------

def get(user_id: int, limit: int = 10) -> list[dict]:
    """
    Вернуть последние `limit` сообщений пользователя для формирования промпта.
    """
    # .get(user_id, []) — вернёт пустой список, если юзера нет.
    # [-limit:] — берем только последние N сообщений.
    # list(...) — возвращаем копию, чтобы код не мог случайно изменить кэш.
    return list(_histories.get(user_id, [])[-limit:])


# -------------------------------------------------------------------
# 6. Очистка истории
# -------------------------------------------------------------------

async def clear(user_id: int) -> None:
    """Удалить всю историю пользователя (например, для команды /reset)."""
    async with _lock:
        _histories.pop(user_id, None)  # pop с default — не падает, если нет
        _save()