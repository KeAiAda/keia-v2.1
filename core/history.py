# core/history.py
# -------------------------------------------------------------------
# История диалогов.
# Хранит последние N сообщений для каждого пользователя.
# В памяти (dict) + на диске (JSON), чтобы не терять между запусками.
# -------------------------------------------------------------------

import asyncio
# asyncio — для Lock, чтобы два одновременных запроса не попортили историю.

from core import config
from core import storage

# -------------------------------------------------------------------
# 1. Состояние
# -------------------------------------------------------------------

# Кэш в памяти: {user_id: [сообщение, сообщение, ...]}
# Читается из файла один раз при init(), потом все операции с ней.
_histories: dict[int, list[dict]] = {}

# Флаг: инициализировались ли уже
_initialized = False

# Блокировка: пока один поток пишет, другой ждёт.
# asyncio.Lock работает внутри одного event loop (у нас один — ок).
_lock = asyncio.Lock()

# Сколько последних сообщений хранить.
# 20 = 10 пар user/assistant. При токенах: ~1500-2000 токенов.
MAX_HISTORY = 20


# -------------------------------------------------------------------
# 2. Инициализация
# -------------------------------------------------------------------

def init() -> None:
    """
    Загрузить историю из файла в память.
    Вызывается один раз при старте приложения.
    """
    global _histories, _initialized

    # Если уже загружено — не грузим повторно.
    if _initialized:
        return

    # load_json вернёт {} если файла нет или он битый — не упадёт.
    raw = storage.load_json(config.HISTORY_FILE, default={})

    # В JSON ключи — строки. Нам удобнее числа (user_id — это int).
    # Конвертируем каждый ключ в int.
    _histories = {int(k): v for k, v in raw.items()}

    _initialized = True


# -------------------------------------------------------------------
# 3. Внутренняя функция: сохранить на диск
# -------------------------------------------------------------------

def _save() -> None:
    """
    Записать текущий _histories в файл.
    Внутренняя — вызывается из add() и clear().
    """
    # JSON требует строковых ключей. Конвертируем int → str.
    to_save = {str(k): v for k, v in _histories.items()}

    # atomic_write_json сам создаст папку, если надо.
    storage.atomic_write_json(config.HISTORY_FILE, to_save)


# -------------------------------------------------------------------
# 4. Добавить сообщение
# -------------------------------------------------------------------

async def add(user_id: int, role: str, content: str) -> None:
    """
    Добавить одно сообщение в историю пользователя.
    role: "user" или "assistant".
    """
    # Берём блокировку. Если другой вызов уже внутри — этот подождёт.
    async with _lock:
        # Убедимся, что для этого пользователя есть список.
        # setdefault: если ключа нет — создаст с пустым списком.
        _histories.setdefault(user_id, []).append({
            "role": role,
            "content": content,
        })

        # Обрезаем до последних MAX_HISTORY сообщений.
        # [-MAX_HISTORY:] — взять последние N элементов списка.
        _histories[user_id] = _histories[user_id][-MAX_HISTORY:]

        # Сохраняем на диск.
        _save()


# -------------------------------------------------------------------
# 5. Получить историю
# -------------------------------------------------------------------

def get(user_id: int, limit: int = 10) -> list[dict]:
    """
    Вернуть последние `limit` сообщений пользователя.
    Возвращает копию (не ссылку), чтобы вызывающий код не мог случайно
    испортить наш кэш.
    """
    # .get(user_id, []) — вернёт [] если пользователя нет.
    # [-limit:] — последние limit элементов.
    # list(...) — создать копию списка.
    return list(_histories.get(user_id, [])[-limit:])


# -------------------------------------------------------------------
# 6. Очистить историю
# -------------------------------------------------------------------

async def clear(user_id: int) -> None:
    """
    Удалить всю историю пользователя.
    Полезно для команды /reset.
    """
    async with _lock:
        _histories.pop(user_id, None)   # pop с default — не падает, если нет
        _save()